#!/usr/bin/env python3
"""Generate cmd/stream/app/src/bandCalibration.ts from a mindlights CSV log.

The radar in the web UI plots each EEG band against its own distribution
instead of a shared axis. This script produces that distribution: 101
percentile knots per band, taken from a reference recording.

    ./hack/scripts/gen-band-calibration.py ../reggie-eeg-2026-08-04.csv

By default the leading rows with no attention/meditation are skipped - the
headset emits band power before it has locked on, and those samples skew the
low end. Pass --from 0 to keep them.
"""

import argparse
import csv
import pathlib
import sys

COLUMNS = [
    "eegdelta", "eegtheta", "eeglowalpha", "eeghighalpha",
    "eeglowbeta", "eeghighbeta", "eeglowgamma", "eeghighgamma",
]
NAMES = [
    "delta", "theta", "lowAlpha", "highAlpha",
    "lowBeta", "highBeta", "lowGamma", "highGamma",
]

# Column -> band for logs written before the EEG_POWER parser offset fix.
#
# ParseMindflex read the band payload at data[k:k+3] rather than
# data[n+k:n+k+3], so "eegdelta" holds the packet header bytes
# [pad, 0x83, 0x18] = 33560 on every sample, every real band landed one column
# to the right, and true high gamma was never recorded at all. Keep this in step
# with legacyBandShift in cmd/stream/replay.go.
SHIFTED = {
    "delta": "eegtheta",
    "theta": "eeglowalpha",
    "lowAlpha": "eeghighalpha",
    "highAlpha": "eeglowbeta",
    "lowBeta": "eeghighbeta",
    "highBeta": "eeglowgamma",
    "lowGamma": "eeghighgamma",
    "highGamma": None,          # never made it into the log
}
UNSHIFTED = dict(zip(NAMES, COLUMNS))

OUT = pathlib.Path(__file__).resolve().parents[2] / "cmd/stream/app/src/bandCalibration.ts"


def quantile(values, p):
    """Linear-interpolated quantile; values must be sorted."""
    i = (len(values) - 1) * p
    lo = int(i)
    hi = min(lo + 1, len(values) - 1)
    return values[lo] + (values[hi] - values[lo]) * (i - lo)


def load(path):
    """One sample per second, dropping rows with no band data."""
    rows = list(csv.DictReader(open(path)))
    if not rows:
        sys.exit(f"{path}: no rows")
    missing = [c for c in COLUMNS if c not in rows[0]]
    if missing:
        sys.exit(f"{path}: missing column(s) {', '.join(missing)}")

    seen = set()
    out = []
    for r in rows:
        ts = int(r["timestamp"])
        if ts in seen or not r[COLUMNS[0]].strip():
            continue
        seen.add(ts)
        out.append((ts, {c: int(r[c]) for c in COLUMNS}, r["attention"].strip()))
    return out


def first_locked_offset(samples):
    """Seconds from the start until attention first appears."""
    t0 = samples[0][0]
    for ts, _, att in samples:
        if att:
            return ts - t0
    return 0


def wrap(numbers, indent="    ", width=96):
    lines, cur = [], indent
    for n in numbers:
        tok = f"{n}, "
        if len(cur) + len(tok) > width:
            lines.append(cur.rstrip())
            cur = indent
        cur += tok
    lines.append(cur.rstrip().rstrip(","))
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", help="mindlights CSV log to calibrate from")
    ap.add_argument("--from", dest="start", type=int, default=None,
                    help="skip the first N seconds (default: up to first attention sample)")
    ap.add_argument("-o", "--out", default=str(OUT))
    ap.add_argument("--no-legacy-band-shift", dest="shift", action="store_false",
                    help="CSV was recorded after the parser offset fix")
    args = ap.parse_args()
    mapping = UNSHIFTED if not args.shift else SHIFTED

    samples = load(args.csv)
    t0 = samples[0][0]
    start = args.start if args.start is not None else first_locked_offset(samples)
    valid = [s for s in samples if s[0] - t0 >= start]
    if len(valid) < 100:
        sys.exit(f"only {len(valid)} samples after skipping {start}s - too few to calibrate")

    name = pathlib.Path(args.csv).name
    out = [
        f"// Percentile knots per EEG band, derived from {name}",
        f"// ({len(valid)} samples; the first {start}s skipped - no attention lock yet).",
        "//",
        f"// Legacy band-column shift: {'applied' if args.shift else 'not applied'}."
        " See gen-band-calibration.py.",
        "//",
        "// The radar plots each band against its own distribution rather than a shared",
        "// axis: raw band power spans three orders of magnitude and is strongly",
        "// right-skewed, so a shared linear axis is dominated by whichever band is",
        "// largest and tells you nothing about the rest.",
        "//",
        "// Generated by hack/scripts/gen-band-calibration.py - do not edit by hand.",
        "",
        "export const BAND_ORDER = [",
        "  " + ", ".join(f'"{n}"' for n in NAMES),
        "] as const;",
        "",
        "export type BandName = typeof BAND_ORDER[number];",
        "",
        "// knots[b][i] is the i-th percentile of band b, i = 0..100",
        "const KNOTS: Record<string, number[]> = {",
    ]
    for n in NAMES:
        col = mapping[n]
        if col is None:
            # No data for this band in this log; emit a flat zero so the UI's
            # isDeadBand() drops it instead of drawing a fake trace.
            knots = [0] * 101
        else:
            v = sorted(s[1][col] for s in valid)
            knots = [round(quantile(v, j / 100)) for j in range(101)]
        out.append(f"  {n}: [")
        out.extend(wrap(knots))
        out.append("  ],")
    out.append("};")
    out.append("")
    out.append('''/**
 * Where `value` falls in this band's own distribution, 0-100.
 * Returns 0 for a band with no spread - a channel the log never captured, or a
 * stuck sensor reporting one value forever.
 */
export function percentileRank(band: string, value: number): number {
  const k = KNOTS[band];
  if (!k) return 0;
  if (k[100] === k[0]) return 0;
  if (value <= k[0]) return 0;
  if (value >= k[100]) return 100;
  let lo = 0;
  let hi = 100;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (k[mid] <= value) {
      lo = mid;
    } else {
      hi = mid;
    }
  }
  const span = k[hi] - k[lo];
  return lo + (span ? (value - k[lo]) / span : 0);
}

/** True when the band never moves in the reference recording. */
export function isDeadBand(band: string): boolean {
  const k = KNOTS[band];
  return !!k && k[0] === k[100];
}''')

    pathlib.Path(args.out).write_text("\n".join(out) + "\n")
    dead = [n for n in NAMES
            if mapping[n] is None or len({s[1][mapping[n]] for s in valid}) <= 8]
    print(f"wrote {args.out} from {len(valid)} samples (skipped {start}s)")
    if dead:
        print(f"  warning: dead channel(s): {', '.join(dead)}")


if __name__ == "__main__":
    main()
